/// Session tree filter mode (pi FilterMode). Pure discriminated enum, not serialized.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FilterMode {
    /// Default: hide settings/bookkeeping entries.
    Default,
    /// On top of the default, also hide tool results.
    NoTools,
    /// User messages only.
    UserOnly,
    /// Entries with labels only.
    LabeledOnly,
    /// Show everything.
    All,
}

/// FilterMode → display value string (shared with settings-selector item values).
pub fn filter_mode_to_str(mode: FilterMode) -> &'static str {
    match mode {
        FilterMode::Default => "default",
        FilterMode::NoTools => "no-tools",
        FilterMode::UserOnly => "user-only",
        FilterMode::LabeledOnly => "labeled-only",
        FilterMode::All => "all",
    }
}

/// Display value string → FilterMode (shared with settings-selector on_change mapping; unknown falls back to Default).
pub fn filter_mode_from_str(s: &str) -> FilterMode {
    match s {
        "no-tools" => FilterMode::NoTools,
        "user-only" => FilterMode::UserOnly,
        "labeled-only" => FilterMode::LabeledOnly,
        "all" => FilterMode::All,
        _ => FilterMode::Default,
    }
}

/// Flat node in the tree display (generated by layering entries + filtering + collapse/search).
struct TreeFlatNode {
    id: String,
    depth: usize,
    entry: SessionTreeEntry,
    label: Option<String>,
    has_children: bool,
    is_expanded: bool,
}

impl TreeFlatNode {
    /// Short summary (shown in the title line + source for search text).
    fn summary(&self) -> String {
        match &self.entry {
            SessionTreeEntry::Message { message, .. } => message_summary(message),
            SessionTreeEntry::Label { label: Some(l), .. } => format!("label: {l}"),
            SessionTreeEntry::BranchSummary { summary, .. } => summary.clone(),
            SessionTreeEntry::Compaction { summary, .. } => summary.clone(),
            SessionTreeEntry::SessionInfo { name: Some(n), .. } => n.clone(),
            other => kind_name(other).to_string(),
        }
    }

    /// Search text = label + summary + id.
    fn searchable_text(&self) -> String {
        format!(
            "{} {} {}",
            self.label.as_deref().unwrap_or(""),
            self.summary(),
            self.id
        )
    }

    fn kind_marker(&self) -> &'static str {
        match &self.entry {
            SessionTreeEntry::Message { message, .. } => match message {
                Message::User(_) => "U",
                Message::Assistant(_) => "A",
                Message::ToolResult(_) => "T",
            },
            SessionTreeEntry::Label { .. } => "L",
            SessionTreeEntry::BranchSummary { .. } => "B",
            SessionTreeEntry::Compaction { .. } => "C",
            _ => "·",
        }
    }

    fn kind_color_token(&self) -> ColorToken {
        match &self.entry {
            SessionTreeEntry::Message { message, .. } => match message {
                Message::User(_) => ColorToken::UserMessageText,
                Message::Assistant(a) => {
                    // Lines with no text that use error_message as the summary use error color
                    // (Aligned with pi: errorMessage is displayed in error color; when text exists, use normal color)
                    let has_text = a
                        .content
                        .iter()
                        .any(|c| matches!(c, ContentBlock::Text(t) if !t.text.trim().is_empty()));
                    let error_fallback = !has_text
                        && !matches!(a.stop_reason, StopReason::Aborted)
                        && a.error_message
                            .as_deref()
                            .is_some_and(|e| !normalize_single_line(e).is_empty());
                    if error_fallback {
                        ColorToken::Error
                    } else {
                        ColorToken::ThinkingText
                    }
                }
                Message::ToolResult(_) => ColorToken::ToolOutput,
            },
            _ => ColorToken::Muted,
        }
    }
}

fn kind_name(e: &SessionTreeEntry) -> &'static str {
    match e {
        SessionTreeEntry::Message { .. } => "message",
        SessionTreeEntry::ThinkingLevelChange { .. } => "thinking",
        SessionTreeEntry::ModelChange { .. } => "model",
        SessionTreeEntry::ActiveToolsChange { .. } => "tools",
        SessionTreeEntry::Compaction { .. } => "compaction",
        SessionTreeEntry::BranchSummary { .. } => "branch",
        SessionTreeEntry::Custom { .. } => "custom",
        SessionTreeEntry::CustomMessage { .. } => "custom-message",
        SessionTreeEntry::Label { .. } => "label",
        SessionTreeEntry::SessionInfo { .. } => "session-info",
        SessionTreeEntry::Leaf { .. } => "leaf",
    }
}

/// Maximum character count for error summaries in tree lines (aligned with pi: errorMessage.slice(0, 80)).
const MAX_ERROR_SUMMARY_CHARS: usize = 80;

/// Single-line normalization (aligned with pi normalize: replace newlines/tabs with spaces, then trim).
fn normalize_single_line(s: &str) -> String {
    s.replace(['\n', '\t'], " ").trim().to_string()
}

fn message_summary(message: &Message) -> String {
    match message {
        Message::User(u) => text_of(&u.content),
        Message::Assistant(a) => {
            let text = a
                .content
                .iter()
                .filter_map(|c| match c {
                    ContentBlock::Text(t) if !t.text.trim().is_empty() => Some(t.text.clone()),
                    _ => None,
                })
                .collect::<Vec<_>>()
                .join(" ");
            if !text.is_empty() {
                return text;
            }
            // Textless fallback chain (aligned with the assistant branch of pi getEntryDisplayText, same order):
            // aborted → "(aborted)"; has error_message → normalize and truncate to 80 chars; otherwise "(no content)"
            if matches!(a.stop_reason, StopReason::Aborted) {
                return "(aborted)".to_string();
            }
            if let Some(err) = a.error_message.as_deref() {
                let normalized = normalize_single_line(err);
                if !normalized.is_empty() {
                    return normalized.chars().take(MAX_ERROR_SUMMARY_CHARS).collect();
                }
            }
            "(no content)".to_string()
        }
        Message::ToolResult(t) => t
            .content
            .iter()
            .filter_map(|c| match c {
                ContentBlock::Text(t) if !t.text.trim().is_empty() => Some(t.text.clone()),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join(" "),
    }
}

fn text_of(blocks: &zen_ai::types::ContentBlockList) -> String {
    match blocks {
        zen_ai::types::ContentBlockList::Text(s) => s.clone(),
        zen_ai::types::ContentBlockList::Blocks(bs) => bs
            .iter()
            .filter_map(|b| match b {
                ContentBlock::Text(t) => Some(t.text.clone()),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join(" "),
    }
}

/// Whether this is a settings/bookkeeping entry hidden by the default filter (aligned with pi isSettingsEntry).
fn is_settings_entry(e: &SessionTreeEntry) -> bool {
    matches!(
        e,
        SessionTreeEntry::Label { .. }
            | SessionTreeEntry::Custom { .. }
            | SessionTreeEntry::ModelChange { .. }
            | SessionTreeEntry::ThinkingLevelChange { .. }
            | SessionTreeEntry::SessionInfo { .. }
    )
}

/// Session tree navigation overlay: ASCII tree + search + collapse/expand + label editing + filter —
/// Shown on the /tree command (T-AP-11-1); input is the current branch entry slice (it builds its own hierarchy and FlatNode internally).
#[allow(clippy::type_complexity)] // Callback fields (Box<dyn FnMut> composition)
pub struct TreeSelectorComponent {
    entries: Vec<SessionTreeEntry>,
    current_leaf_id: Option<String>,
    theme: Theme,
    app_kb: KeybindingsManager<AppAction>,
    on_select: Option<Box<dyn FnMut(String)>>,
    on_cancel: Option<Box<dyn FnMut()>>,
    on_label_change: Option<Box<dyn FnMut(String, Option<String>)>>,

    filter_mode: FilterMode,
    query: String,
    show_timestamps: bool,
    flat: Vec<TreeFlatNode>,
    selected_index: usize,
    expanded: HashSet<String>,
    empty_cancelled: bool,

    label_mode: bool,
    label_input: Input,
    label_target: Option<String>,
    top_border: DynamicBorder,
    bottom_border: DynamicBorder,
}

impl TreeSelectorComponent {
    /// Construct the tree selector; an empty tree (no visible nodes) triggers on_cancel at construction (aligned with pi setTimeout semantics).
    /// **Owned conversion (T-AP-08-5)**: entry snapshots/theme/app keybinding table are held by value (constructor clones/preloads),
    /// Allows the component to be stored in `InteractiveUi` mount fields (avoids self-referential borrow, following the SettingsSelectorComponent precedent).
    #[allow(clippy::too_many_arguments, clippy::type_complexity)]
    pub fn new(
        entries: Vec<SessionTreeEntry>,
        current_leaf_id: Option<&str>,
        terminal_height: u16,
        theme: Theme,
        app_kb: KeybindingsManager<AppAction>,
        on_select: Option<Box<dyn FnMut(String)>>,
        on_cancel: Option<Box<dyn FnMut()>>,
        on_label_change: Option<Box<dyn FnMut(String, Option<String>)>>,
        initial_selected_id: Option<String>,
        initial_filter_mode: FilterMode,
    ) -> Self {
        let _max_visible = std::cmp::max(5, terminal_height / 2);
        let border = Style::fg(theme.fg(ColorToken::Border));
        let mut comp = TreeSelectorComponent {
            entries,
            current_leaf_id: current_leaf_id.map(|s| s.to_string()),
            theme,
            app_kb,
            on_select,
            on_cancel,
            on_label_change,
            filter_mode: initial_filter_mode,
            query: String::new(),
            show_timestamps: false,
            flat: Vec::new(),
            selected_index: 0,
            expanded: HashSet::new(),
            empty_cancelled: false,
            label_mode: false,
            label_input: Input::new(),
            label_target: None,
            top_border: DynamicBorder::new(border.clone()),
            bottom_border: DynamicBorder::new(border),
        };
        // Expand all entries with children by default (aligned with pi: initially all expanded, collapsible).
        for e in &comp.entries {
            let has_children = comp.entries.iter().any(|x| x.parent_id() == Some(e.id()));
            if has_children {
                comp.expanded.insert(e.id().to_string());
            }
        }
        comp.rebuild();
        // Empty tree → cancel immediately (pi: setTimeout(() => onCancel(), 100))
        if comp.flat.is_empty() {
            comp.empty_cancelled = true;
            let cancel = comp.on_cancel.take();
            if let Some(mut cb) = cancel {
                cb();
            }
        }
        // Initial selection (aligned with pi `initialSelectedId ?? currentLeafId` + `findNearestVisibleIndex`):
        // Default to the current leaf — after user navigation/summarization, reopening /tree should place the cursor at the new leaf position (e.g., branch summary entry);
        // If the target is filtered out and invisible, walk up the parent chain to the nearest visible ancestor; if all are invisible → last line (same as pi).
        if !comp.flat.is_empty() {
            let mut current = initial_selected_id.or_else(|| comp.current_leaf_id.clone());
            let mut placed = false;
            while let Some(id) = current {
                if let Some(idx) = comp.flat.iter().position(|n| n.id == id) {
                    comp.selected_index = idx;
                    placed = true;
                    break;
                }
                current = comp
                    .entries
                    .iter()
                    .find(|e| e.id() == id)
                    .and_then(entry_parent_id);
            }
            if !placed {
                comp.selected_index = comp.flat.len() - 1;
            }
        }
        comp
    }

    /// Expand all (initial default: collapse all branches except the current path).
    #[allow(clippy::type_complexity)] // Hierarchy/label table is locally large
    fn rebuild(&mut self) {
        let mut by_parent: HashMap<Option<String>, Vec<&SessionTreeEntry>> = HashMap::new();
        for e in &self.entries {
            let pid = entry_parent_id(e);
            by_parent.entry(pid).or_default().push(e);
        }
        // Order preserved: in original `entries` order
        for list in by_parent.values_mut() {
            list.sort_by_key(|e| entry_index(&self.entries, e));
        }

        // Branch point child sorting (aligned with pi flattenTree's containsActive priority):
        // First build roots in original order, then post-order collect from each root the node set whose subtree contains the current leaf,
        // Then stably sort each branch point's child list and the root list — those containing the current leaf come first, the rest keep their original relative order.
        // Effect: after summarize, the newest summary (current leaf) appears next to the return point instead of after the entire abandoned chain.
        // When the leaf is None (e.g., navigated to root), the set is empty = all original order (same as pi).
        let mut roots: Vec<&SessionTreeEntry> = self
            .entries
            .iter()
            .filter(|e| match entry_parent_id(e) {
                Some(pid) => !self.entries.iter().any(|x| x.id() == pid),
                None => true,
            })
            .collect();
        fn collect_contains_active<'x>(
            e: &'x SessionTreeEntry,
            by_parent: &HashMap<Option<String>, Vec<&'x SessionTreeEntry>>,
            leaf: Option<&str>,
            out: &mut HashSet<&'x str>,
        ) -> bool {
            let mut has = leaf == Some(e.id());
            if let Some(children) = by_parent.get(&Some(e.id().to_string())) {
                for c in children {
                    if collect_contains_active(c, by_parent, leaf, out) {
                        has = true;
                    }
                }
            }
            if has {
                out.insert(e.id());
            }
            has
        }
        let mut contains_active: HashSet<&str> = HashSet::new();
        for r in &roots {
            collect_contains_active(
                r,
                &by_parent,
                self.current_leaf_id.as_deref(),
                &mut contains_active,
            );
        }
        for list in by_parent.values_mut() {
            list.sort_by_key(|e| !contains_active.contains(e.id()));
        }
        roots.sort_by_key(|e| !contains_active.contains(e.id()));

        // 2. label index (Label entry → target_id)
        let mut labels: HashMap<&str, String> = HashMap::new();
        for e in &self.entries {
            if let SessionTreeEntry::Label {
                target_id,
                label: Some(l),
                ..
            } = e
            {
                labels.insert(target_id.as_str(), l.clone());
            }
        }

        // 3. DFS flatten (subtree of collapsed node skipped entirely)
        // Indentation rules ported from pi flattenTree (tree-selector.ts):
        // - Parent branch (>1 child) → child level +1
        // - First generation after a branch (just_branched and not at root level) → +1 (visual grouping of subtree)
        // - Other single-child chains → flat, no increase (entries in linear long sessions stay at the same level)
        let search_tokens: Vec<String> = self
            .query
            .to_lowercase()
            .split_whitespace()
            .map(|s| s.to_string())
            .collect();

        let mut flat: Vec<TreeFlatNode> = Vec::new();

        fn walk<'x>(
            e: &'x SessionTreeEntry,
            depth: usize,
            just_branched: bool,
            by_parent: &HashMap<Option<String>, Vec<&'x SessionTreeEntry>>,
            expanded: &HashSet<String>,
            flat: &mut Vec<TreeFlatNode>,
            labels: &HashMap<&'x str, String>,
        ) {
            let children = by_parent
                .get(&Some(e.id().to_string()))
                .cloned()
                .unwrap_or_default();
            let has_children = !children.is_empty();
            let is_expanded = expanded.contains(e.id());
            flat.push(TreeFlatNode {
                id: e.id().to_string(),
                depth,
                entry: e.clone(),
                label: labels.get(e.id()).cloned(),
                has_children,
                is_expanded,
            });
            let multiple_children = children.len() > 1;
            let child_depth = if multiple_children || (just_branched && depth > 0) {
                depth + 1
            } else {
                depth
            };
            if is_expanded {
                for child in children {
                    walk(
                        child,
                        child_depth,
                        multiple_children,
                        by_parent,
                        expanded,
                        flat,
                        labels,
                    );
                }
            }
        }
        for r in roots {
            walk(r, 0, false, &by_parent, &self.expanded, &mut flat, &labels);
        }

        // 4. Filter (pi filterNodes logic)
        let current_leaf = self.current_leaf_id.clone();
        flat.retain(|n| {
            let is_current = current_leaf.as_deref() == Some(n.id.as_str());
            // Hide non-current assistant messages that are pure tool calls and non-error
            if let SessionTreeEntry::Message {
                message: Message::Assistant(a),
                ..
            } = &n.entry
            {
                if !is_current {
                    let has_text = a
                        .content
                        .iter()
                        .any(|c| matches!(c, ContentBlock::Text(t) if !t.text.trim().is_empty()));
                    let is_err = matches!(a.stop_reason, StopReason::Error | StopReason::Aborted);
                    if !has_text && !is_err {
                        return false;
                    }
                }
            }
            let settings = is_settings_entry(&n.entry);
            let passes = match self.filter_mode {
                FilterMode::UserOnly => matches!(
                    &n.entry,
                    SessionTreeEntry::Message {
                        message: Message::User(_),
                        ..
                    }
                ),
                FilterMode::NoTools => {
                    !settings
                        && !matches!(
                            &n.entry,
                            SessionTreeEntry::Message {
                                message: Message::ToolResult(_),
                                ..
                            }
                        )
                }
                FilterMode::LabeledOnly => n.label.is_some(),
                FilterMode::All => true,
                FilterMode::Default => !settings,
            };
            if !passes {
                return false;
            }
            if !search_tokens.is_empty() {
                let text = n.searchable_text().to_lowercase();
                return search_tokens.iter().all(|t| text.contains(t));
            }
            true
        });
        if flat.is_empty() {
            self.selected_index = 0;
        } else if self.selected_index >= flat.len() {
            self.selected_index = flat.len() - 1;
        }
        self.flat = flat;
    }

    fn selected(&self) -> Option<&TreeFlatNode> {
        self.flat.get(self.selected_index)
    }

    fn move_selection(&mut self, delta: isize) {
        let len = self.flat.len();
        if len == 0 {
            return;
        }
        self.selected_index =
            ((self.selected_index as isize + delta).rem_euclid(len as isize)) as usize;
    }

    fn toggle_fold(&mut self) {
        // Extract data needed for the check before mutating (avoid conflict between `selected()` borrow and `expanded` mutation)
        let Some(n) = self.selected().map(|n| (n.id.clone(), n.has_children)) else {
            return;
        };
        let (id, has_children) = n;
        if !has_children {
            return;
        }
        if self.expanded.contains(&id) {
            self.expanded.remove(&id);
        } else {
            self.expanded.insert(id.clone());
        }
        // Keep selection on the current node after expand/collapse
        self.rebuild();
        if let Some(idx) = self.flat.iter().position(|x| x.id == id) {
            self.selected_index = idx;
        }
    }

    /// Switch filter mode and rebuild the tree (effect point of `app.tree.filter.*`).
    fn set_filter_mode(&mut self, mode: FilterMode) {
        if self.filter_mode != mode {
            self.filter_mode = mode;
            self.rebuild();
        }
    }

    /// Current visible node count.
    pub fn visible_count(&self) -> usize {
        self.flat.len()
    }

    /// Current filter.
    pub fn filter_mode(&self) -> FilterMode {
        self.filter_mode
    }

    fn enter_label_edit(&mut self) {
        if self.on_label_change.is_none() {
            return;
        }
        if let Some((id, label)) = self.selected().map(|n| (n.id.clone(), n.label.clone())) {
            self.label_target = Some(id);
            self.label_input.set_value(label.unwrap_or_default());
            self.label_mode = true;
        }
    }

    fn submit_label(&mut self) {
        let id = self.label_target.clone().unwrap_or_default();
        let value = self.label_input.get_value().trim().to_string();
        let label = if value.is_empty() { None } else { Some(value) };
        self.label_mode = false;
        self.label_target = None;
        if let Some(cb) = &mut self.on_label_change {
            cb(id, label);
        }
        self.rebuild();
    }
}

/// Entry parent id (delegates to existing `SessionTreeEntry::parent_id` in zen-core).
fn entry_parent_id(e: &SessionTreeEntry) -> Option<String> {
    e.parent_id().map(|s| s.to_string())
}

/// Entry ISO timestamp (truncated to HH:MM:SS for display).
fn entry_timestamp_str(e: &SessionTreeEntry) -> String {
    let ts = match e {
        SessionTreeEntry::Message { timestamp, .. }
        | SessionTreeEntry::ThinkingLevelChange { timestamp, .. }
        | SessionTreeEntry::ModelChange { timestamp, .. }
        | SessionTreeEntry::ActiveToolsChange { timestamp, .. }
        | SessionTreeEntry::Compaction { timestamp, .. }
        | SessionTreeEntry::BranchSummary { timestamp, .. }
        | SessionTreeEntry::Custom { timestamp, .. }
        | SessionTreeEntry::CustomMessage { timestamp, .. }
        | SessionTreeEntry::Label { timestamp, .. }
        | SessionTreeEntry::SessionInfo { timestamp, .. }
        | SessionTreeEntry::Leaf { timestamp, .. } => timestamp,
    };
    ts.chars().skip(11).take(8).collect()
}

fn entry_index(entries: &[SessionTreeEntry], e: &SessionTreeEntry) -> usize {
    entries.iter().position(|x| x.id() == e.id()).unwrap_or(0)
}

impl Component for TreeSelectorComponent {
    fn render(&mut self, buf: &mut ScreenBuffer, x: u16, y: u16, width: u16, height: u16) -> u16 {
        let theme = &self.theme;
        let accent = Style::fg(theme.fg(ColorToken::Accent));
        let muted = Style::fg(theme.fg(ColorToken::Muted));
        let mut painted = 0u16;
        macro_rules! take {
            ($n:expr) => {{
                let remaining = height - painted;
                if height - painted == 0 {
                    return painted;
                }
                let step = ($n).min(remaining);
                if step > 0 {
                    painted += step;
                }
            }};
        }
        macro_rules! line {
            ($text:expr, $style:expr, $indent:expr) => {{
                if height - painted == 0 {
                    return painted;
                }
                buf.fill(x, y + painted, width, 1, &Style::default());
                buf.write(x + $indent, y + painted, $style, $text);
                take!(1);
            }};
        }

        if height > painted {
            let n = self
                .top_border
                .render(buf, x, y + painted, width, height - painted);
            take!(n);
        }
        line!("Session Tree", &accent, 1);
        if height > painted {
            buf.fill(x, y + painted, width, 1, &Style::default());
            take!(1);
        }
        let search_note = if self.query.is_empty() {
            String::new()
        } else {
            format!("search: {}", self.query)
        };
        let ts_note = if self.show_timestamps {
            " · timestamps"
        } else {
            ""
        };
        let header = format!(
            "filter {} · {} nodes · {}{}",
            filter_mode_to_str(self.filter_mode),
            self.flat.len(),
            search_note,
            ts_note
        );
        line!(&header, &muted, 1);
        if height > painted {
            buf.fill(x, y + painted, width, 1, &Style::default());
            take!(1);
        }

        if self.label_mode {
            // Label edit state: input line
            buf.fill(x, y + painted, width, 1, &Style::default());
            buf.write(x + 1, y + painted, &muted, "label:");
            take!(1);
            if height > painted {
                let n = self.label_input.render(
                    buf,
                    x + 1,
                    y + painted,
                    width.saturating_sub(1),
                    height - painted,
                );
                take!(n);
            }
        } else {
            // Tree row window
            let total = self.flat.len();
            let view = (height - painted) as usize;
            let half = view / 2;
            let start = if self.selected_index < half {
                0
            } else if self.selected_index + half >= total {
                total.saturating_sub(view).min(total)
            } else {
                self.selected_index - half
            };
            let end = (start + view).min(total);
            for i in start..end {
                if height - painted == 0 {
                    break;
                }
                let node = &self.flat[i];
                let is_selected = i == self.selected_index;
                buf.fill(x, y + painted, width, 1, &Style::default());
                let sel_style = if is_selected {
                    Style::fg(theme.fg(ColorToken::Muted))
                } else {
                    Style::default()
                };
                buf.write(x, y + painted, &sel_style, " ");
                // Indent + connector
                let indent = "  ".repeat(node.depth);
                let connector = if node.has_children {
                    if node.is_expanded {
                        "▾ "
                    } else {
                        "▸ "
                    }
                } else {
                    "  "
                };
                let marker = node.kind_marker();
                let ts = if self.show_timestamps {
                    format!("{} ", entry_timestamp_str(&node.entry))
                } else {
                    String::new()
                };
                let label = node.label.as_deref().unwrap_or("");
                let summary = node.summary();
                // label prefix has a trailing space separator (aligned with pi: `[${label}] `), content always follows
                // (Previously, when label existed, summary was set empty, causing content loss)
                let label_part = if label.is_empty() {
                    String::new()
                } else {
                    format!("[{label}] ")
                };
                let text = format!("{indent}{connector}[{marker}] {ts}{label_part}{summary}");
                let style = if is_selected {
                    accent.clone()
                } else {
                    Style::fg(theme.fg(node.kind_color_token()))
                };
                buf.write(x + 2, y + painted, &style, &text);
                take!(1);
            }
        }

        if height > painted {
            buf.fill(x, y + painted, width, 1, &Style::default());
            take!(1);
        }
        if height > painted {
            let n = self
                .bottom_border
                .render(buf, x, y + painted, width, height - painted);
            take!(n);
        }
        painted
    }

    fn handle_key(&mut self, key: &crossterm::event::KeyEvent) -> bool {
        if self.label_mode {
            let is_escape = matches!(
                (key.code, key.modifiers),
                (crossterm::event::KeyCode::Esc, _)
                    | (
                        crossterm::event::KeyCode::Char('c'),
                        crossterm::event::KeyModifiers::CONTROL,
                    )
            );
            if is_escape {
                self.label_mode = false;
                return true;
            }
            let consumed = self.label_input.handle_key(key);
            if consumed && key.code == crossterm::event::KeyCode::Enter {
                self.submit_label();
            }
            return consumed;
        }

        // 1. app actions
        if let Some(kid) = KeyId::from_key_event(*key) {
            for action in [
                AppAction::TreeFoldOrUp,
                AppAction::TreeUnfoldOrDown,
                AppAction::TreeEditLabel,
                AppAction::TreeToggleLabelTimestamp,
                AppAction::TreeFilterDefault,
                AppAction::TreeFilterNoTools,
                AppAction::TreeFilterUserOnly,
                AppAction::TreeFilterLabeledOnly,
                AppAction::TreeFilterAll,
                AppAction::TreeFilterCycleForward,
                AppAction::TreeFilterCycleBackward,
            ] {
                if self.app_kb.matches(&kid, action) {
                    return match action {
                        AppAction::TreeFoldOrUp => {
                            if self.selected().is_some_and(|n| n.has_children) {
                                self.toggle_fold();
                            } else {
                                self.move_selection(-1);
                            }
                            true
                        }
                        AppAction::TreeUnfoldOrDown => {
                            if self
                                .selected()
                                .is_some_and(|n| n.has_children && !n.is_expanded)
                            {
                                self.toggle_fold();
                            } else {
                                self.move_selection(1);
                            }
                            true
                        }
                        AppAction::TreeEditLabel => {
                            self.enter_label_edit();
                            true
                        }
                        AppAction::TreeToggleLabelTimestamp => {
                            self.show_timestamps = !self.show_timestamps;
                            true
                        }
                        AppAction::TreeFilterDefault => {
                            self.set_filter_mode(FilterMode::Default);
                            true
                        }
                        AppAction::TreeFilterNoTools => {
                            self.set_filter_mode(FilterMode::NoTools);
                            true
                        }
                        AppAction::TreeFilterUserOnly => {
                            self.set_filter_mode(FilterMode::UserOnly);
                            true
                        }
                        AppAction::TreeFilterLabeledOnly => {
                            self.set_filter_mode(FilterMode::LabeledOnly);
                            true
                        }
                        AppAction::TreeFilterAll => {
                            self.set_filter_mode(FilterMode::All);
                            true
                        }
                        AppAction::TreeFilterCycleForward => {
                            self.set_filter_mode(cycle_filter(self.filter_mode, 1));
                            true
                        }
                        AppAction::TreeFilterCycleBackward => {
                            self.set_filter_mode(cycle_filter(self.filter_mode, -1));
                            true
                        }
                        _ => false,
                    };
                }
            }
        }

        // 2. select key
        match (key.code, key.modifiers) {
            (crossterm::event::KeyCode::Up, _) => {
                self.move_selection(-1);
                true
            }
            (crossterm::event::KeyCode::Down, _) => {
                self.move_selection(1);
                true
            }
            (crossterm::event::KeyCode::Enter, _) => {
                if let Some(n) = self.selected() {
                    let id = n.id.clone();
                    if let Some(cb) = &mut self.on_select {
                        cb(id);
                    }
                }
                true
            }
            (crossterm::event::KeyCode::Esc, _)
            | (crossterm::event::KeyCode::Char('c'), crossterm::event::KeyModifiers::CONTROL) => {
                if let Some(cb) = &mut self.on_cancel {
                    cb();
                }
                true
            }
            _ => {
                // 3. Search input (printable char / backspace)
                match key.code {
                    crossterm::event::KeyCode::Char(c)
                        if !key
                            .modifiers
                            .contains(crossterm::event::KeyModifiers::CONTROL)
                            && !key.modifiers.contains(crossterm::event::KeyModifiers::ALT) =>
                    {
                        self.query.push(c);
                        self.rebuild();
                        true
                    }
                    crossterm::event::KeyCode::Backspace => {
                        self.query.pop();
                        self.rebuild();
                        true
                    }
                    _ => false,
                }
            }
        }
    }
}

/// Cycle filter mode (Ctrl+O / Ctrl+I).
fn cycle_filter(mode: FilterMode, delta: isize) -> FilterMode {
    const ORDER: [FilterMode; 5] = [
        FilterMode::Default,
        FilterMode::NoTools,
        FilterMode::UserOnly,
        FilterMode::LabeledOnly,
        FilterMode::All,
    ];
    let idx = ORDER.iter().position(|m| *m == mode).unwrap_or(0) as isize;
    ORDER[((idx + delta).rem_euclid(ORDER.len() as isize)) as usize]
}

