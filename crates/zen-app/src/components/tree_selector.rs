    #[test]
    fn label_edit_flow() {
        let entries = vec![entry("e1", None, user_msg("hello"))];
        let changed = std::rc::Rc::new(std::cell::RefCell::new(None::<(String, String)>));
        let changed_captured = changed.clone();
        let kb = kb();
        let mut comp = TreeSelectorComponent::new(
            entries.clone(),
            None,
            20,
            theme(),
            kb.clone(),
            None,
            None,
            Some(Box::new(move |id, label| {
                *changed_captured.borrow_mut() = Some((id, label.unwrap_or_default()))
            })),
            None,
            FilterMode::Default,
        );
        let shift_l = crossterm::event::KeyEvent::new(
            crossterm::event::KeyCode::Char('L'),
            crossterm::event::KeyModifiers::SHIFT,
        );
        assert!(comp.handle_key(&shift_l));
        assert!(comp.label_mode);
        // Type "mylabel" then press Enter
        for c in "mylabel".chars() {
            comp.handle_key(&crossterm::event::KeyEvent::from(
                crossterm::event::KeyCode::Char(c),
            ));
        }
        let enter = crossterm::event::KeyEvent::from(crossterm::event::KeyCode::Enter);
        assert!(comp.handle_key(&enter));
        assert_eq!(
            *changed.borrow(),
            Some(("e1".to_string(), "mylabel".to_string()))
        );
        assert!(!comp.label_mode);
    }

